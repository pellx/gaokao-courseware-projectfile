def seg(*p):
    return [list(x) for x in p]

def relax(x0, y0, y1, k=0.08, x1=1.0, n=30):
    return [[round(x0 + (x1 - x0) * i / n, 4), round(y1 + (y0 - y1) * math.exp(-(x1 - x0) * i / n / k), 4)] for i in range(n + 1)]

