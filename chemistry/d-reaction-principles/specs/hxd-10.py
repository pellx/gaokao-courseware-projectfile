def strong(x):
    V = 40 * x
    net = 0.1 * (20 - V) / (20 + V)
    h = (net + math.sqrt(net * net + 4e-14)) / 2
    return -math.log10(h) / 14

def weak(x):
    V = 40 * x
    pka = 4.76
    if V < 19.9:
        ph = max(2.88, pka + math.log10(max(V, 1e-6) / (20 - V)))
    elif V <= 20.1:
        ph = 8.73
    else:
        ph = max(8.73, 14 + math.log10(0.1 * (V - 20) / (20 + V)))
    return ph / 14

