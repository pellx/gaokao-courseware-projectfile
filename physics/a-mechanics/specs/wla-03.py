def stairs(x0, x1, y0, y1, n):
    # 把 [x0, x1] 分成 n 段，每段取左端点的速度当作匀速（微元示意）
    out = []
    for i in range(n):
        xa = x0 + (x1 - x0) * i / n
        xb = x0 + (x1 - x0) * (i + 1) / n
        y = y0 + (y1 - y0) * i / n
        out += [[round(xa, 4), round(y, 4)], [round(xb, 4), round(y, 4)]]
    return out


