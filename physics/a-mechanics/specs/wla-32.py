import math
F0 = 0.45  # 固有频率在横轴上的位置


def amp(x, z=0.12):
    r = max(x, 1e-4) / F0
    return 1 / math.sqrt((1 - r * r) ** 2 + (2 * z * r) ** 2)


PEAK = amp(F0)
RES = lambda x: 0.06 + 0.84 * amp(x) / PEAK
DAMP = lambda x: 0.5 + 0.38 * math.exp(-2.6 * x) * math.sin(2 * math.pi * x / 0.16)

